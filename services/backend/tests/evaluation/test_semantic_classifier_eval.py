"""Semantic classifier evaluation harness — golden-pinned regression gate.

Runs the deterministic keyword classifier (``engine.classify_event``) against
the committed golden set (``goldens/semantic_classifier_golden.json``): expected
stance, intent, sentiment-valence sign, and abstention behavior per case.

Measured baseline (deterministic-semantic-classifier@1.0.0, 2026-07-23, 69
cases): overall accuracy 1.00, per-stance recall 1.00 for every stance group,
abstention correctness 1.00 — every golden expectation was generated by running
the case through the real engine and reviewing the output, never aspirationally.
The floors below sit just under the measured baseline so benign golden-set
additions don't flap, while any keyword/threshold regression still fails here.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from typing import Any, Optional

from services.semantic_intelligence.engine import classify_event
from services.semantic_intelligence.models import (
    ObservationStatus,
    SemanticObservation,
    SentimentObservation,
)

_GOLDEN_PATH = Path(__file__).parent / "goldens" / "semantic_classifier_golden.json"

# Floors pinned to the measured baseline above (1.00 across the board).
OVERALL_ACCURACY_FLOOR = 0.95
PER_STANCE_RECALL_FLOOR = 0.90
ABSTENTION_CORRECTNESS_FLOOR = 1.0

TENANT = "tenant_eval"


def _golden_cases() -> list[dict[str, Any]]:
    doc = json.loads(_GOLDEN_PATH.read_text(encoding="utf-8"))
    return doc["cases"]


async def _classify(case: dict[str, Any]) -> tuple[SemanticObservation, list[SentimentObservation]]:
    payload = {
        "source_event_id": f"evt_eval_{case['id']}",
        "source_type": "feedback",
        "actor_ref": "eval_user",
        "actor_type": "profile",
        "primary_subject_ref": "prod_eval",
        "target_type": "product",
        "content": case["text"],
        "language": case.get("language", "en"),
    }
    return await classify_event(payload, TENANT)


def _valence_sign(sentiments: list[SentimentObservation]) -> Optional[str]:
    if not sentiments:
        return None
    valence = sentiments[0].valence
    if valence > 0:
        return "positive"
    if valence < 0:
        return "negative"
    return "zero"


async def _case_correct(case: dict[str, Any]) -> tuple[bool, str]:
    """Full-label correctness for a non-abstain case (stance + intent + valence sign)."""
    obs, sentiments = await _classify(case)
    expected = case["expected"]
    actual = {
        "stance": obs.stance.value,
        "intent": obs.intent.value,
        "valence_sign": _valence_sign(sentiments),
    }
    wanted = {k: expected[k] for k in ("stance", "intent", "valence_sign")}
    return actual == wanted, f"{case['id']}: actual={actual} expected={wanted}"


class TestSemanticClassifierEval:
    """Golden-set accuracy suite for the deterministic semantic classifier."""

    def test_golden_set_shape(self):
        """The committed set stays large enough to be meaningful per group."""
        cases = _golden_cases()
        assert len(cases) >= 60
        by_group: dict[str, int] = defaultdict(int)
        for case in cases:
            expected = case["expected"]
            by_group["abstain" if expected["abstain"] else expected["stance"]] += 1
        assert by_group["abstain"] >= 8
        for stance in ("supportive", "opposed", "neutral"):
            assert by_group[stance] >= 10, f"{stance} group shrank below 10 cases"

    async def test_overall_accuracy(self):
        """Overall stance+intent+valence accuracy on classified cases (measured 1.00)."""
        cases = [c for c in _golden_cases() if not c["expected"]["abstain"]]
        results = [await _case_correct(c) for c in cases]
        correct = sum(1 for ok, _ in results if ok)
        accuracy = correct / len(cases)
        assert accuracy >= OVERALL_ACCURACY_FLOOR, (
            f"accuracy {accuracy:.1%} ({correct}/{len(cases)}) below "
            f"{OVERALL_ACCURACY_FLOOR:.0%} floor:\n"
            + "\n".join(f"  FAIL {detail}" for ok, detail in results if not ok)
        )

    async def test_per_stance_recall(self):
        """Stance recall per expected-stance group (measured 1.00 each)."""
        by_stance: dict[str, list[dict[str, Any]]] = defaultdict(list)
        for case in _golden_cases():
            if not case["expected"]["abstain"]:
                by_stance[case["expected"]["stance"]].append(case)

        failures: list[str] = []
        for stance, cases in by_stance.items():
            correct = 0
            for c in cases:
                obs, _ = await _classify(c)
                if obs.stance.value == c["expected"]["stance"]:
                    correct += 1
            recall = correct / len(cases)
            if recall < PER_STANCE_RECALL_FLOOR:
                failures.append(f"  {stance}: recall={recall:.1%} ({correct}/{len(cases)})")
        assert not failures, (
            f"per-stance recall below {PER_STANCE_RECALL_FLOOR:.0%}:\n" + "\n".join(failures)
        )

    async def test_abstention_correctness(self):
        """Abstention behavior is structural — it must stay exact (measured 1.00).

        Every abstain case abstains with the expected reason and zero sentiment;
        every classified case actually classifies.
        """
        failures: list[str] = []
        checks = 0
        for case in _golden_cases():
            obs, sentiments = await _classify(case)
            expected = case["expected"]
            checks += 1
            if expected["abstain"]:
                if obs.status is not ObservationStatus.ABSTAINED:
                    failures.append(f"  {case['id']}: status={obs.status.value} != abstained")
                elif obs.abstention_reason != expected["abstention_reason"]:
                    failures.append(
                        f"  {case['id']}: reason={obs.abstention_reason!r} "
                        f"!= {expected['abstention_reason']!r}"
                    )
                elif sentiments:
                    failures.append(f"  {case['id']}: abstention emitted sentiment rows")
            elif obs.status is not ObservationStatus.CLASSIFIED:
                failures.append(f"  {case['id']}: status={obs.status.value} != classified")
        correctness = (checks - len(failures)) / checks
        assert correctness >= ABSTENTION_CORRECTNESS_FLOOR, (
            f"abstention correctness {correctness:.1%} below "
            f"{ABSTENTION_CORRECTNESS_FLOOR:.0%}:\n" + "\n".join(failures)
        )

#!/usr/bin/env python3
"""Deterministic CI baseline inventory (CI V2, WO-CI-002).

Reads the working tree only (no network) and emits the workflow x trigger x
artifact matrix, test-file counts and suite-registry lane counts. Output is
stable so it can be diffed before and after the CI V2 deletions.

    python scripts/ci_baseline.py --format markdown
    python scripts/ci_baseline.py --format csv
"""
from __future__ import annotations

import argparse
import collections
import csv
import io
import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
WORKFLOWS = ROOT / ".github" / "workflows"
TEST_FILE = re.compile(r"(^|/)(test_[^/]*\.py|[^/]*_test\.py|[^/]*\.(test|spec)\.(ts|tsx))$")


def _triggers(doc: dict) -> dict:
    # PyYAML parses the bare key `on` as boolean True.
    on = doc.get("on", doc.get(True)) or {}
    if isinstance(on, str):
        return {on: {}}
    if isinstance(on, list):
        return {k: {} for k in on}
    return {k: (v or {}) for k, v in on.items()}


def _steps(doc: dict):
    for job_name, job in (doc.get("jobs") or {}).items():
        for step in job.get("steps") or []:
            yield job_name, step


def workflow_rows() -> list[dict]:
    rows = []
    for path in sorted(WORKFLOWS.glob("*.y*ml")):
        text = path.read_text()
        doc = yaml.safe_load(text) or {}
        trig = _triggers(doc)
        pr = trig.get("pull_request") or {}
        uploads = downloads = 0
        for _, step in _steps(doc):
            uses = str(step.get("uses", ""))
            uploads += uses.startswith("actions/upload-artifact")
            downloads += uses.startswith("actions/download-artifact")
        rows.append({
            "workflow": path.name,
            "lines": text.count("\n") + 1,
            "jobs": len(doc.get("jobs") or {}),
            "events": "+".join(sorted(str(k) for k in trig)),
            "pr_types": "+".join(pr.get("types", [])) if pr else "",
            "pr_path_filtered": bool(pr.get("paths")) if pr else False,
            "uploads": uploads,
            "downloads": downloads,
        })
    return rows


def test_file_counts() -> dict[str, int]:
    files = subprocess.run(
        ["git", "ls-files"], cwd=ROOT, check=True, capture_output=True, text=True
    ).stdout.splitlines()
    counts: collections.Counter[str] = collections.Counter()
    for f in files:
        if TEST_FILE.search(f):
            counts[f.rsplit(".", 1)[-1]] += 1
    return dict(sorted(counts.items()))


def suite_lane_counts() -> dict[str, int]:
    doc = yaml.safe_load((ROOT / "config" / "test_suites.yaml").read_text())
    suites = doc.get("suites", doc) if isinstance(doc, dict) else doc
    items = suites if isinstance(suites, list) else list(suites.values())
    return dict(sorted(collections.Counter(str(s.get("lane")) for s in items).items()))


def render_markdown(rows, tests, lanes) -> str:
    out = ["# CI baseline inventory", "",
           "Generated by `scripts/ci_baseline.py` from the working tree.", "",
           f"- Workflow files: **{len(rows)}** ({sum(r['lines'] for r in rows)} lines)",
           f"- Artifact uploads / downloads: **{sum(r['uploads'] for r in rows)}** / "
           f"**{sum(r['downloads'] for r in rows)}**",
           f"- Test files: {', '.join(f'{k}={v}' for k, v in tests.items())}",
           f"- Registered suites by lane: {', '.join(f'{k}={v}' for k, v in lanes.items())}", "",
           "| Workflow | Lines | Jobs | Events | PR types | PR path-filtered | Up | Down |",
           "|---|---:|---:|---|---|---|---:|---:|"]
    for r in rows:
        out.append(f"| `{r['workflow']}` | {r['lines']} | {r['jobs']} | {r['events']} | "
                   f"{r['pr_types'] or '-'} | {'yes' if r['pr_path_filtered'] else 'no'} | "
                   f"{r['uploads']} | {r['downloads']} |")
    return "\n".join(out) + "\n"


def render_csv(rows) -> str:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=list(rows[0]), lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    return buf.getvalue()


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--format", choices=["markdown", "csv"], default="markdown")
    ap.add_argument("--output")
    args = ap.parse_args(argv)
    rows = workflow_rows()
    text = (render_csv(rows) if args.format == "csv"
            else render_markdown(rows, test_file_counts(), suite_lane_counts()))
    if args.output:
        Path(args.output).write_text(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
